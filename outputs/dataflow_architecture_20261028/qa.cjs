const {chromium}=require('/Users/yuntzuyu/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('fs');const path=require('path');const {pathToFileURL,fileURLToPath}=require('url');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[],remote=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
 await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
 await page.locator('.node').first().waitFor();
 if(await page.locator('.node').count()!==12)throw Error('CDW graph node count');
 await page.locator('.node[data-node="stage"]').click();
 if(!(await page.locator('#inspector').innerText()).includes('stage_bundle()'))throw Error('Node detail not updated');
 await page.locator('#tab-formal').click();
 if(!(await page.locator('#view-title').innerText()).includes('Formal'))throw Error('Formal mode switch');
 await page.locator('.step-line[data-node="compute"]').click();
 if(!(await page.locator('#inspector').innerText()).includes('calculate_report()'))throw Error('Sequence detail not updated');
 await page.locator('#tab-legacy').click();
 if(await page.locator('.node').count()!==10)throw Error('Legacy graph node count');
 await page.locator('.node[data-node="model"]').click();
 if(!(await page.locator('#inspector').innerText()).includes('client.messages.create()'))throw Error('Legacy detail');
 await page.locator('#tab-case').click();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(__dirname,'desktop.png'),fullPage:true});
 const hrefs=await page.locator('a[href]').evaluateAll(es=>es.map(x=>x.href));
 const missing=hrefs.filter(x=>x.startsWith('file:')).filter(x=>!fs.existsSync(fileURLToPath(x)));
 if(missing.length)throw Error('Missing local links: '+missing.join(','));
 await page.setViewportSize({width:390,height:1000});await page.evaluate(()=>window.scrollTo(0,0));
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(overflow)throw Error('Mobile document overflows');
 await page.screenshot({path:path.join(__dirname,'mobile.png')});
 if(errors.length||remote.length)throw Error(JSON.stringify({errors,remote}));
 const result={desktop:'1440x1100',mobile:'390x1000',viewsChecked:3,graphSelection:true,functionSelection:true,localLinksChecked:hrefs.length,allLocalLinksExist:true,externalRequests:remote.length,javascriptErrors:errors.length,mobileDocumentOverflow:overflow};
 fs.writeFileSync(path.join(__dirname,'qa.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
