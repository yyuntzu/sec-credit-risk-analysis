# Explicit reviewed search candidates for these working papers only. Every label is
# checked in its own statement block, and every source locator is retained.
LABELS = {
    'revenue': ('IS', 'Revenues'), 'cost_of_revenue': ('IS', 'Operating Cost'),
    'gross_profit': ('IS', 'Gross Profit'), 'operating_expense': ('IS', 'Operating Expense'),
    'operating_income': ('IS', 'Operating Profit'), 'interest_expense': ('IS', 'Interest Expense'),
    'pretax_profit': ('IS', 'Pre-tax Profit (Loss)'), 'income_tax': ('IS', 'Income Tax Expense(Credit)'),
    'net_income': ('IS', 'After-tax Net Profit (Loss)'),
    'beginning_cash': ('CF', 'Cash and cash equivalents - beginning of period'),
    'ending_cash': ('CF', 'Cash and cash equivalents - end of period'),
    'cfo': ('CF', 'Net cash generated by (used in) operating activities'),
    'cfi': ('CF', 'Net cash generated by (used in) investing activities'),
    'cff': ('CF', 'Net cash generated by (used in) financing activities'),
    'current_assets': ('BS', 'Current Assets'), 'current_liabilities': ('BS', 'Current Liabilities'),
    'total_liabilities': ('BS', 'Total Liabilities'), 'net_worth': ('BS', 'Total Net Worth'),
    'capitalized_interest': ('SUPPORT', 'Capitalized Interest'), 'da': ('SUPPORT', 'Depreciation & Amortization'),
}
BLOCKS = {'BS': (10, 73), 'IS': (80, 117), 'SUPPORT': (118, 125), 'CF': (129, 194), 'RATIO': (196, 233)}
COLUMNS = ('D', 'I', 'M', 'R')
CF_PERIOD_REASON = 'CF區未重列期間；上方IS期間是否同樣適用及現金定義尚未核實，候選數值保留於來源清單'


def decimal_cell(value):
    if value is None or value == '': return None
    if isinstance(value, bool): raise ValueError('Boolean is not a financial source value')
    text = str(value).strip().replace(',', '')
    if text in ('N.A.', 'N/A', '-'): return None
    if text.startswith('(') and text.endswith(')'): text = '-' + text[1:-1]
    if not re.fullmatch(r'[+-]?\d+(?:\.\d+)?', text):
        raise ValueError(f'Not an explicit numeric source cell: {value!r}')
    number = Decimal(text)
    if not number.is_finite(): raise ValueError('Nonfinite source')
    return number


def read_workbook(path, review_date):
    try:
        import xlrd
    except ImportError as exc:
        raise ImportError('讀取原始.xls需要選用依賴：python -m pip install -r scripts/requirements-workbook-review.txt') from exc
    path = Path(path).resolve(); digest = hashlib.sha256(path.read_bytes()).hexdigest()
    book = xlrd.open_workbook(str(path)); sheet = book.sheet_by_name('Report1')
    if sheet.cell_value(0, 0) != '(Consolidated)Balance Sheet': raise ValueError('Workbook consolidation scope changed')
    title = sheet.cell_value(3, 0)
    if title != 'Customer Name: NEXSTAR MEDIA GROUP, INC.': raise ValueError('Nexstar borrower identity mismatch')
    if sheet.cell_value(3, 14) != 'Unit: USD  thousand': raise ValueError('Currency/unit not confirmed from O4')
    entity = title.removeprefix('Customer Name: ')
    def get(cell):
        m = re.fullmatch(r'([A-Z]+)(\d+)', cell)
        col = 0
        for char in m[1]: col = col * 26 + ord(char) - 64
        return sheet.cell_value(int(m[2])-1, col-1)
    labels = {}
    for block, (low, high) in BLOCKS.items():
        for r in range(low, high+1):
            label = str(get(f'A{r}'))
            if label: labels.setdefault((block, label), []).append(r)
    def locate(block, label):
        hits = labels.get((block, label), [])
        if len(hits) != 1: raise ValueError(f'Ambiguous/missing original label: {block}/{label}: {hits}')
        return hits[0]
    observations = []
    for (block, label), rows in labels.items():
        for r in rows:
            for col in COLUMNS:
                observations.append({'source_path': str(path), 'sha256': digest, 'sheet': sheet.name,
                    'statement': block, 'original_label': label, 'label_cell': f'A{r}', 'value_cell': f'{col}{r}',
                    'raw_value': get(f'{col}{r}'), 'column': col, 'currency': 'USD', 'scale': '1000',
                    'balance_header': get(f'{col}6'), 'duration_header': get(f'{col}76')})
    return {'path': path, 'hash': digest, 'entity': entity, 'get': get, 'locate': locate,
            'observations': observations, 'review_date': review_date}


def build_inputs(book, mode, quarter=None):
    get, locate = book['get'], book['locate']; entity = book['entity']; scope = 'consolidated'
    roles = ANNUAL_ROLES if mode == 'annual' else QUARTERLY_ROLES
    periods = []
    source_id = 'workbook:' + book['hash']
    calendar = Evidence('calendar:' + book['hash'], entity, scope, source_id, book['hash'], book['review_date'],
        f"{book['path']}#Report1!D6:R6,D76:R76,O4,A1,A4", 'calendar', roles,
        'Read-only local workbook review snapshot; actual column date strings, USD thousand and consolidated entity checked. '
        'This date is the review-snapshot date, not the unknown SEC filing/publication date. Company SEC fiscal calendar not independently verified.')
    for i, (role, col) in enumerate(zip(roles, COLUMNS)):
        raw = get(f'{col}76'); match = re.fullmatch(r'(\d{4}-\d{2}-\d{2})~(\d{4}-\d{2}-\d{2})', str(raw))
        if not match: raise ValueError('Unverified actual duration header')
        start, end = map(date.fromisoformat, match.groups())
        if end > book['review_date']: raise ValueError('Source period ends after review snapshot date')
        if str(get(f'{col}6')) != end.isoformat(): raise ValueError('BS and IS ending dates disagree')
        interim = mode == 'quarterly' and i in (1, 3)
        if interim and quarter not in (1, 2, 3): raise ValueError('Explicit source-identified quarter required')
        # The workbook gives no actual LTM start for interim columns. Never guess.
        periods.append(Period(role, f'{start}～{end}', start.year, start, end, None if interim else start,
            (calendar.id,), quarter if interim else None,
            'Interim LTM start and full components not supplied/verified in source workbook' if interim else ''))
    report = empty_report(mode, entity=entity, scope=scope, currency='USD', scale=Decimal(1000),
                          periods=tuple(periods), evidence={calendar.id: calendar})
    candidates, inputs = {}, {}
    by_role = {p.role: (p, col) for p, col in zip(periods, COLUMNS)}
    slots = dict(report.facts)
    # Auxiliary inputs reuse existing METRICS; no ad-hoc codes for working-paper details.
    for p in periods:
        for metric in ('current_assets', 'current_liabilities', 'total_liabilities', 'quick_assets', 'net_worth', 'capitalized_interest', 'da'):
            slots[f'input:{metric}:{p.role}'] = None
    for fid, f in slots.items():
        metric, role = (f.metric, f.period_role) if f else (fid.split(':')[1], fid.split(':')[2])
        p, col = by_role[role]; spec = METRICS[metric]
        start = None if spec.period_kind in ('instant', 'opening') else p.ltm_start if spec.period_kind == 'ltm' else p.start
        end = p.start - timedelta(days=1) if spec.period_kind == 'opening' else p.end
        unit = f.unit if f else spec.unit
        item = {'metric': metric, 'period_role': role, 'start': start, 'end': end, 'unit': unit,
                'currency': 'USD' if unit == 'money' else None, 'scale': '1000' if unit == 'money' else '1',
                'period_kind': 'instant' if spec.period_kind in ('instant', 'opening') else 'duration',
                'status': 'missing', 'value': None, 'candidate_ids': [], 'evidence_ids': [], 'basis': '',
                'reason': '既有底稿未提供可核實的來源科目／組成；不等於SEC未揭露'}
        if ':pct:' in fid or spec.formula:
            item.update(status='not_calculable', reason='Required formula inputs/definitions not yet verified')
        elif metric in LABELS:
            block, label = LABELS[metric]; row = locate(block, label); cell = f'{col}{row}'
            raw = get(cell); value = decimal_cell(raw)
            eid = f"workbook:{book['hash']}:{cell}"
            candidates[eid] = {'id': eid, 'entity': entity, 'scope': scope, 'source_id': source_id, 'version': book['hash'],
                'document_date': book['review_date'].isoformat(), 'locator': f"{book['path']}#Report1!{cell}; label=A{row}; dates={col}6,{col}76; unit=O4",
                'definition': label, 'value': str(value) if value is not None else None,
                'unit': 'USD', 'scale': '1000', 'basis': '', 'status': 'sourced' if value is not None else 'missing',
                'excerpt': f'{label}: {raw!r}; consolidation=A1; entity=A4; period={get(col+"76")}; raw cell retained',
                'source_url': str(book['path']), 'reason': '原始儲存格空白／無可用數值' if value is None else ''}
            item.update(candidate_ids=[eid], evidence_ids=[eid], status='sourced' if value is not None else 'missing',
                        value=str(value) if value is not None else None, reason='原始儲存格空白／無可用數值' if value is None else '')
            if block == 'CF': item.update(status='not_calculable', value=None, reason=CF_PERIOD_REASON)
            if metric == 'operating_expense':
                item.update(status='not_calculable', value=None, reason='Operating Expense 包含／排除COGS及完整範圍未核實；原值保留於來源清單')
        inputs[fid] = item
    return report, inputs, candidates


def reconciliation_checks(book):
    """Arithmetic diagnostics only. No inferred FX/Other or accepted Net Worth policy."""
    get, locate = book['get'], book['locate']; checks = []
    def source(block, label, col):
        row = locate(block, label); cell = f'{col}{row}'
        return decimal_cell(get(cell)), f"{book['path']}#Report1!{cell}"
    def compare(kind, col, terms, reported, reason, tolerance=Decimal(0), unit='money'):
        values = [v for v, _ in terms]; observed, reported_id = reported
        base = {'kind': kind, 'period': get(col+'76'), 'column': col, 'unit': unit, 'currency': 'USD' if unit == 'money' else None, 'scale': '1000' if unit == 'money' else '1',
                'source_locators': [ref for _, ref in terms]+[reported_id], 'reason': reason}
        if observed is None or any(v is None for v in values):
            checks.append({**base, 'status': 'not_calculable', 'calculated_value': None, 'reported_value': observed, 'difference': None})
        else:
            calculated = sum(values); delta = calculated-observed
            checks.append({**base, 'status': 'matched' if delta == 0 else 'within_precision' if abs(delta) <= tolerance else 'unexplained_difference',
                           'calculated_value': calculated, 'reported_value': observed, 'difference': delta, 'tolerance': tolerance})
    previous_end = None
    for col in COLUMNS:
        opening = source('CF', LABELS['beginning_cash'][1], col); ending = source('CF', LABELS['ending_cash'][1], col)
        change = source('CF', 'Net Cash Inflow (outflow) for current period', col)
        negative_opening = (None if opening[0] is None else -opening[0], opening[1])
        compare('cash_end_minus_begin_vs_reported_change', col, [ending, negative_opening], change,
                '底稿列示數值的算術差額；CF期間與同口徑仍待SEC現金及受限制現金附註核實，不宣稱財報錯誤')
        flows = [source('CF', LABELS[m][1], col) for m in ('cfo', 'cfi', 'cff')]
        fx = source('CF', 'Effects Of Exchange Rate Variation', col)
        compare('cash_complete_bridge', col, flows+[fx], change,
                'FX空白不是0；其他調節項與CF期間未核實，不反推未知項')
        # Even an explicit FX value cannot establish unknown other adjustments.
        checks[-1].update(status='not_calculable', calculated_value=None, difference=None)
        compare('three_activity_subtotal_vs_reported_change', col, flows, change,
                '僅為三類已列活動小計的殘差，非完整現金勾稽；FX與其他項目未知')
        if previous_end is not None:
            # Only annual-contiguous intervals; never compare an FY-end to a
            # different-column YTD opening as though columns were four quarters.
            prev_end, prev_date = previous_end
            start = date.fromisoformat(str(get(col+'76')).split('~')[0])
            if prev_date + timedelta(days=1) == start:
                compare('prior_end_vs_current_opening', col, [prev_end], opening,
                        '跨期現金定義與限制現金待核；差額採前期末－本期期初')
        previous_end = (ending, date.fromisoformat(str(get(col+'76')).split('~')[1]))
        assets = source('BS', 'Total Assets', col); liabilities = source('BS', 'Total Liabilities', col)
        equity = source('BS', 'Total Net Worth', col)
        compare('printed_balance_sheet_equation', col, [liabilities, equity], assets,
                '僅核對原表列示總額；不核准DEC-02 Net Worth／租賃／合併定義')
        # Independently rounded source ratio has 0.01 percentage-point precision.
        ca = source('BS', 'Current Assets', col); cl = source('BS', 'Current Liabilities', col)
        ratio_row = locate('RATIO', 'Current Ratio'); raw_ratio = str(get(f'{col}{ratio_row}'))
        original_ratio = Decimal(raw_ratio.removesuffix('%')) / 100 if re.fullmatch(r'[+-]?\d+(\.\d+)?%', raw_ratio) else None
        ratio = ca[0]/cl[0] if ca[0] is not None and cl[0] not in (None, 0) else None
        compare('CF-01_source_ratio', col, [(ratio, ca[1]+'; '+cl[1])], (original_ratio, f"{book['path']}#Report1!{col}{ratio_row}"),
                '比率以小數儲存；來源顯示精度0.01百分點，差額為計算－來源', Decimal('0.00005'), unit='percent')
    return checks


def run_nexstar_workbook(path, mode, output_dir, review_date, quarter=None):
    book = read_workbook(path, review_date)
    report, inputs, candidates = build_inputs(book, mode, quarter)
    checks = reconciliation_checks(book)
    limitations = ['來源為使用者e-loan工作底稿，未取得／核驗對應SEC原始申報與CIK；不得標為SEC已核驗報告',
                   '原檔未提供公布日期；Evidence日期為本機覆核快照日期，不能用於證明歷史as-of可用性',
                   'CF期間未重列，財務定義、完整現金橋接及DEC待確認事項尚未完成']
    report, acceptance = complete_report(report, inputs, candidates, checks=checks, limitations=limitations)
    outputs = write_report_artifacts(report, acceptance, output_dir,
        source_bundle={'inputs': inputs, 'evidence': candidates, 'provenance_limits': limitations})
    Path(output_dir, 'original_cells.json').write_text(json.dumps(book['observations'], ensure_ascii=False, indent=2, default=str), encoding='utf-8')
    return report, acceptance, outputs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('workbook'); parser.add_argument('--mode', choices=('annual', 'quarterly'), required=True)
    parser.add_argument('--quarter', type=int, choices=(1, 2, 3)); parser.add_argument('--review-date', type=date.fromisoformat, required=True)
    parser.add_argument('--output-dir', required=True)
    args = parser.parse_args(argv)
    try:
        _, acceptance, outputs = run_nexstar_workbook(args.workbook, args.mode, args.output_dir, args.review_date, args.quarter)
    except (ImportError, ValueError, OSError) as exc:
        import sys
        print(json.dumps({'status': 'error', 'error': str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1
    print(json.dumps({'status': 'review_artifacts_generated', **outputs, 'acceptance_blockers': acceptance['acceptance_blockers']}, ensure_ascii=False, default=str))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
